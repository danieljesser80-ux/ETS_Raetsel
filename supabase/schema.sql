create or replace function public.admin_form_groups(p_code text) returns jsonb
language plpgsql security definer set search_path = public, extensions, pg_temp
as $$
declare
  r public.round;
  n int; k int; base int; rem int; sz int;
  pids uuid[];
  gnames text[];
  gid int; wid int; w text; nm text;
  pos int; i int; j int; mi int;
  members uuid[];
  lets text[];
  letter_counts int[];
  tmp text;
  used int[];
begin
  if not public.is_admin_code(p_code) then return jsonb_build_object('ok', false, 'reason', 'nicht_berechtigt'); end if;
  perform pg_advisory_xact_lock(hashtext('raetsel_join'));
  select * into r from public.round where id = 1 for update;
  if r.phase <> 'anmeldung' then return jsonb_build_object('ok', false, 'reason', 'falsche_phase'); end if;
  if not (r.closed_early or (r.registration_deadline is not null and public.app_now() >= r.registration_deadline)) then
    return jsonb_build_object('ok', false, 'reason', 'anmeldung_offen');
  end if;

  select count(*) into n from public.players;
  if n < r.group_min then return jsonb_build_object('ok', false, 'reason', 'zu_wenige'); end if;
  k := public.group_count(n, r.group_min, r.group_max);
  if k is null then return jsonb_build_object('ok', false, 'reason', 'nicht_teilbar'); end if;

  select array_agg(id order by random()) into pids from public.players;
  select coalesce(array_agg(name), '{}') into gnames from (select name from public.group_names order by random() limit k) s;

  base := n / k; rem := n % k; pos := 1; used := '{}';
  for i in 1..k loop
    sz := base + case when i <= rem then 1 else 0 end;
    members := pids[pos:pos + sz - 1];
    pos := pos + sz;

    nm := case when i <= coalesce(array_length(gnames, 1), 0) then gnames[i] else 'Gruppe ' || i end;
    insert into public.groups (name) values (nm) returning id into gid;
    update public.players set group_id = gid where id = any(members);

    -- OFF-064: jedes Admin-Wort ist unabhängig von der Gruppengröße auswählbar.
    wid := null;
    select id, word into wid, w from public.words where id <> all(used) order by random() limit 1;
    if wid is null then
      select id, word into wid, w from public.words order by random() limit 1;
    end if;
    if wid is null then raise exception 'keine Gruppenwoerter konfiguriert'; end if;
    used := used || wid;
    insert into public.group_tasks (group_id, word_id, solution) values (gid, wid, w);

    -- Alle Buchstaben werden gemischt und möglichst gleichmäßig auf die Mitglieder verteilt.
    select array_agg(c order by random()) into lets from regexp_split_to_table(w, '') c;
    select array_agg(m order by random()) into members from unnest(members) m;
    letter_counts := array_fill(0, ARRAY[sz]);
    for j in 1..char_length(w) loop
      mi := ((j - 1) % sz) + 1;
      letter_counts[mi] := letter_counts[mi] + 1;
      insert into public.letters (player_id, position, letter)
        values (members[mi], letter_counts[mi], lets[j]);
    end loop;
  end loop;

  update public.round set phase = 'wortaufgabe_aktiv', words_started_at = public.app_now(),
    game_deadline = public.app_now() + make_interval(mins => game_minutes), finished_at = null,
    registration_deadline = null, updated_at = public.app_now() where id = 1;
  perform public.set_game_job_active(true);
  return jsonb_build_object('ok', true, 'groups', k);
end $$;

