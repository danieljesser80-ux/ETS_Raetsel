-- ---------------------------------------------------------------- Tabellen
create table if not exists public.round (
  id integer primary key check (id = 1),
  phase text not null default 'vorbereitet'
    check (phase in ('vorbereitet','anmeldung','gruppen_eingeteilt','wortaufgabe_aktiv','aufgabe_abgeschlossen')),
  registration_deadline timestamptz,
  closed_early boolean not null default false,
  updated_at timestamptz not null default now()
);
insert into public.round (id) values (1) on conflict (id) do nothing;

create table if not exists public.admin_config (
  id integer primary key check (id = 1),
  code_hash text
);

create table if not exists public.words (
  id integer generated by default as identity primary key,
  word text not null unique check (word ~ '^[A-Z]+$')
);

create table if not exists public.group_names (
  name text primary key check (length(btrim(name)) > 0)
);

create table if not exists public.groups (
  id integer generated by default as identity primary key,
  name text not null unique
);

create table if not exists public.players (
  id uuid primary key,
  name text not null check (char_length(name) between 2 and 20),
  name_key text not null unique,
  group_id integer references public.groups(id) on delete set null,
  joined_at timestamptz not null default now(),
  check (name_key = lower(btrim(name)))
);
create index if not exists players_group_id_idx on public.players (group_id);

create table if not exists public.group_tasks (
  group_id integer primary key references public.groups(id) on delete cascade,
  word_id integer not null references public.words(id),
  solution text not null
);

create table if not exists public.letters (
  player_id uuid not null references public.players(id) on delete cascade,
  position integer not null check (position >= 1),
  letter text not null check (letter ~ '^[A-Z]$'),
  primary key (player_id, position)
);

create table if not exists public.attempts (
  id bigint generated by default as identity primary key,
  group_id integer not null references public.groups(id) on delete cascade,
  player_id uuid not null references public.players(id) on delete cascade,
  at timestamptz not null,
  correct boolean not null
);
create index if not exists attempts_group_at_idx on public.attempts (group_id, at desc);

create table if not exists public.results (
  group_id integer not null unique references public.groups(id) on delete cascade,
  rank integer not null unique check (rank >= 1),
  points integer not null check (points >= 1),
  player_id uuid not null references public.players(id) on delete cascade,
  solved_at timestamptz not null
);

